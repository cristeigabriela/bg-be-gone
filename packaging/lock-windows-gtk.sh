#!/usr/bin/env bash
# Write packaging/locks/msys2-ucrt64.txt: the exact UCRT64 package files the
# Windows frontend runs on, with their SHA256.
#
# Run it in an MSYS2 shell whose ucrt64 packages are the set you tested (the
# lock is that machine's installed closure, not a fresh resolve). It reads the
# package files from pacman's cache, so it never changes the installation.
# install-windows-gtk.ps1 checks the GTK series; bump $GtkSeries there when the
# new lock moves GTK to another minor version on purpose.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="$ROOT/packaging/locks/msys2-ucrt64.txt"
CACHE=/var/cache/pacman/pkg
P=mingw-w64-ucrt-x86_64

# What the frontend imports; the lock is their closure. webp-pixbuf-loader
# lets GdkPixbuf show and play WebP; the worker previews AVIF and HEIC itself.
pkgs=(gtk4 libadwaita python-gobject python-cairo librsvg adwaita-icon-theme
      hicolor-icon-theme shared-mime-info webp-pixbuf-loader)

closure="$(for p in "${pkgs[@]}"; do pactree -lu "$P-$p"; done | sed 's/[<>=].*//' | sort -u)"

{
  echo "# Generated by packaging/lock-windows-gtk.sh. One line per package file:"
  echo "# its SHA256, two spaces, and its name on repo.msys2.org/mingw/ucrt64/."
  for dep in $closure; do
    # A dependency can name something a package provides; -Qq resolves it.
    name="$(pacman -Qq "$dep")"
    ver="$(pacman -Q "$name" | cut -d' ' -f2)"
    arch="$(pacman -Qi "$name" | sed -n 's/^Architecture *: //p')"
    file="$name-$ver-$arch.pkg.tar.zst"
    local_copy="$CACHE/$file"
    if [ ! -f "$local_copy" ]; then
      local_copy="$(mktemp)"
      curl -fsSL -o "$local_copy" "https://repo.msys2.org/mingw/ucrt64/$file"
    fi
    echo "$(sha256sum "$local_copy" | cut -d' ' -f1)  $file"
  done | sort -k2 -u
} > "$OUT"
echo "==> $OUT ($(grep -vc '^#' "$OUT") packages)"
